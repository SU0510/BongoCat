//! Embedded assets. The generated sprite sheets (resources/insync/sprites)
//! and the alarm chime are compiled into the binary so a released app never
//! depends on the repository layout; `SpriteLibrary::from_embedded` decodes
//! the sheets lazily.

use insync_sprite::SpriteLibrary;
use std::borrow::Cow;
use std::path::PathBuf;
use std::sync::OnceLock;

/// The 32x32 tray icon rendered from the idle frame.
pub fn tray_icon_bytes() -> &'static [u8] {
    include_bytes!("../../../resources/insync/icons/tray.png")
}

/// Mascot images the hub panel draws, by the GPUI asset path it asks for.
///
/// These are cut from the character sheets by `tools/insync-ui/generate_ui_images.py`
/// at exactly the size the panel displays them, so nothing is rescaled at
/// draw time.
fn ui_image(path: &str) -> Option<&'static [u8]> {
    Some(match path {
        "insync/momo_portrait.png" => {
            include_bytes!("../../../resources/insync/ui/momo_portrait.png")
        }
        "insync/momo_wave.png" => include_bytes!("../../../resources/insync/ui/momo_wave.png"),
        "insync/nana_portrait.png" => {
            include_bytes!("../../../resources/insync/ui/nana_portrait.png")
        }
        "insync/nana_wave.png" => include_bytes!("../../../resources/insync/ui/nana_wave.png"),
        _ => return None,
    })
}

/// The asset source the windows are opened with: gpui-kit's icon catalog plus
/// InSync's own embedded mascot images.
pub struct InSyncAssets;

impl gpui_kit::AssetSource for InSyncAssets {
    fn load(&self, path: &str) -> gpui_kit::Result<Option<Cow<'static, [u8]>>> {
        if let Some(bytes) = ui_image(path) {
            return Ok(Some(Cow::Borrowed(bytes)));
        }
        gpui_kit::assets::AllAssets.load(path)
    }

    fn list(&self, path: &str) -> gpui_kit::Result<Vec<gpui_kit::SharedString>> {
        gpui_kit::assets::AllAssets.list(path)
    }
}

/// The alarm chime, generated by `tools/insync-audio/generate_alarm.py`.
pub fn alarm_sound_bytes() -> &'static [u8] {
    include_bytes!("../../../resources/insync/sounds/alarm.wav")
}

/// The path `bongocat-audio` plays the alarm from.
///
/// The audio backend decodes from a path, so the embedded chime is written
/// into the app's private data root and played from there. Returns `None` when
/// that root cannot be written; the notification itself still goes through.
pub fn alarm_sound_path() -> Option<PathBuf> {
    let directory = crate::data_root().join("assets");
    let path = directory.join("alarm.wav");
    let bytes = alarm_sound_bytes();
    if std::fs::metadata(&path).map(|metadata| metadata.len()).ok() != Some(bytes.len() as u64) {
        bongocat_storage::create_private_dir_all(&directory).ok()?;
        bongocat_storage::write_private_atomic(&path, bytes).ok()?;
    }
    Some(path)
}

/// Every character's 13 animation sheets + manifest, compiled in.
pub fn sprite_library() -> &'static SpriteLibrary {
    static LIBRARY: OnceLock<SpriteLibrary> = OnceLock::new();
    LIBRARY.get_or_init(|| {
        let manifest = include_str!("../../../resources/insync/sprites/manifest.json");
        macro_rules! sheets {
            ($character:literal, $( $animation:literal ),+ $(,)?) => {
                Vec::<(&'static str, &'static [u8])>::from([
                    $(
                        (
                            concat!($character, "/", $animation, ".png"),
                            include_bytes!(concat!(
                                "../../../resources/insync/sprites/",
                                $character,
                                "/",
                                $animation,
                                ".png"
                            )) as &'static [u8],
                        ),
                    )+
                ])
            };
        }
        let mut sheets = sheets!(
            "momo",
            "idle", "blink", "wave", "walk", "sleep", "work", "stretch", "react",
            "poke_react", "message_react", "invite_react", "celebrate", "rest"
        );
        sheets.extend(sheets!(
            "momo-mint",
            "idle", "blink", "wave", "walk", "sleep", "work", "stretch", "react",
            "poke_react", "message_react", "invite_react", "celebrate", "rest"
        ));
        sheets.extend(sheets!(
            "nana",
            "idle", "blink", "wave", "walk", "sleep", "work", "stretch", "react",
            "poke_react", "message_react", "invite_react", "celebrate", "rest"
        ));
        SpriteLibrary::from_embedded(manifest, &sheets).expect("embedded sprite manifest valid")
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The chime is played from these exact bytes, so a file the audio backend
    /// cannot decode would leave the alarm silent with nothing to show for it.
    #[test]
    fn alarm_chime_decodes_with_the_audio_backend() {
        use rodio::Source;

        let decoder = rodio::Decoder::try_from(std::io::Cursor::new(alarm_sound_bytes()))
            .expect("embedded alarm chime decodes");
        assert_eq!(decoder.channels().get(), 1);
        assert_eq!(decoder.sample_rate().get(), 44_100);
        let samples: Vec<f32> = decoder.collect();
        assert_eq!(samples.len(), 39_690);
        let peak = samples.iter().fold(0.0_f32, |peak, s| peak.max(s.abs()));
        assert!(peak > 0.5, "chime is too quiet to hear (peak {peak})");
        assert!(peak <= 1.0, "chime clips (peak {peak})");
    }

    /// Every character the setting can name must be fully embedded: a missing
    /// sheet would make the pet fall back to idle frames instead of its
    /// animations, and only a test catches it (the player falls back
    /// silently by design).
    #[test]
    fn every_character_is_fully_embedded() {
        let library = sprite_library();
        for character in crate::store::CHARACTERS {
            let sprites = library
                .character(character)
                .unwrap_or_else(|| panic!("{character} is embedded but not in the library"));
            assert_eq!(sprites.animations.len(), 13, "{character} animations");
        }
    }

    /// The panel draws the portrait and the wave pose from these paths, so a
    /// rename in the generator would leave the panel with an empty avatar and
    /// only this test would say so.
    #[test]
    fn every_panel_image_is_embedded() {
        for character in crate::store::CHARACTERS {
            for role in ["portrait", "wave"] {
                let path = format!("insync/{character}_{role}.png");
                assert!(
                    ui_image(&path).is_some(),
                    "{path} is not embedded; run generate_ui_images.py"
                );
            }
        }
    }
}
